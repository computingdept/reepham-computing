"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const window={};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,"../assets/h446-y13/h446-you-do.js"),"utf8"),{window,location:{pathname:"/test"}});
const {selectGroups,creditedPoints}=window.RHSYouDoLayout;
const sizes=(n,fit,narrow=false)=>Array.from(selectGroups(n,fit,narrow),g=>g.end-g.start);
test("four fits",()=>assert.deepEqual(sizes(4,()=>true),[4]));
test("balanced pairs before three plus one",()=>assert.deepEqual(sizes(4,(_,s)=>s<=3),[2,2]));
test("three plus one when second pair overflows",()=>assert.deepEqual(sizes(4,(i,s)=>i===0&&s<=3),[3,1]));
test("look ahead rather than greedy 3+1+1",()=>assert.deepEqual(sizes(5,(i,s)=> (i===0&&s<=3)||(i===2&&s<=3)),[2,3]));
test("two singles required",()=>assert.deepEqual(sizes(4,(i,s)=>i===0&&s===2),[2,1,1]));
test("diagram isolated",()=>assert.deepEqual(sizes(4,(i,s)=>!(i<=1&&i+s>1)&&s<=4),[1,1,2]));
test("all singles",()=>assert.deepEqual(sizes(4,()=>false),[1,1,1,1]));
test("zero questions",()=>assert.deepEqual(sizes(0,()=>true),[]));
test("six short questions",()=>assert.deepEqual(sizes(6,()=>true),[4,2]));
test("mobile never measures a multi-question screen",()=>assert.deepEqual(sizes(4,()=>{throw Error("unexpected measurement")},true),[1,1,1,1]));
test("marking-point renderer unchanged",()=>assert.equal(creditedPoints("[2] A [1]; B [1].",2).length,2));
